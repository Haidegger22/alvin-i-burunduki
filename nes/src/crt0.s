; Стартовый код для NES (NROM, mapper 0).
; Задачи: заголовок картриджа, инициализация PPU, очистка памяти,
; установка программного стека cc65, обработчик NMI с копированием спрайтов,
; векторы прерываний.
;
; Важное ограничение: инициализированные глобальные переменные в C (сегмент DATA,
; требующий копирования из ПЗУ в ОЗУ) здесь не поддерживаются — вся память уже
; обнулена. Объявляйте переменные без начального значения, константы — через const.
;
; Имена переменных, к которым обращается код на C, начинаются с подчёркивания
; (так cc65 именует символы C) и экспортируются через .exportzp.

.setcpu "6502"
.feature force_range

.import _main               ; точка входа в игре (game.c)
.importzp sp                ; указатель программного стека cc65 (адрес $0005)

; сообщаем линковщику, что стартовый модуль у нас свой: так он не подтянет
; crt0.o из библиотеки cc65 (тот рассчитан на ОЗУ по адресу $6000 и шрифт)
.export __STARTUP__: absolute = 1

; ---------- заголовок картриджа iNES ----------
.segment "HEADER"
    .byte "NES", $1A          ; сигнатура
    .byte 2                   ; 2 банка по 16 КБ программного ПЗУ (32 КБ)
    .byte 1                   ; 1 банк графического ПЗУ (8 КБ)
    .byte $00                 ; mapper 0, зеркалирование горизонтальное
    .byte $00                 ; без дополнительных признаков
    .byte 0, 0, 0, 0, 0, 0, 0, 0

; ---------- переменные в нулевой странице (видны из C) ----------
.exportzp _frame_counter, _scroll_x, _ppu_ctrl_val

.zeropage
_frame_counter: .res 1        ; счётчик кадров, растёт в NMI
_scroll_x:      .res 1        ; прокрутка по горизонтали (пиксели)
_ppu_ctrl_val:  .res 1        ; текущее значение PPUCTRL

; ---------- старт ----------
.segment "STARTUP"
reset:
    sei
    cld
    ldx #$40
    stx $4017                 ; выключаем прерывание кадров APU
    ldx #$ff
    txs                       ; аппаратный стек
    inx                       ; X = 0
    stx $2000                 ; PPU выключен (NMI тоже)
    stx $2001                 ; рендеринг выключен
    stx $4010                 ; выключаем IRQ от DMC
    bit $2002                 ; сбрасываем флаг vblank

    ; ждём первый vblank
:   bit $2002
    bpl :-

    ; чистим оперативную память $0000-$07FF
    lda #0
    ldx #0
clear_ram:
    sta $0000, x
    sta $0100, x
    sta $0200, x
    sta $0300, x
    sta $0400, x
    sta $0500, x
    sta $0600, x
    sta $0700, x
    inx
    bne clear_ram

    ; ждём второй vblank — PPU готов принимать данные
:   bit $2002
    bpl :-

    ; программный стек cc65: указатель sp растёт вниз от $07FF
    ; (адрес самого sp определён библиотекой cc65 — $0005, поэтому пишем по символу)
    lda #$FF
    sta sp
    lda #$07
    sta sp+1

    jmp _main                 ; дальше всё делает код на C

; ---------- обработчик NMI (кадровое прерывание) ----------
nmi:
    pha
    txa
    pha
    tya
    pha

    ; копируем теневой буфер спрайтов $0200-$02FF в OAM через DMA
    lda #$00
    sta $2003
    lda #$02
    sta $4014

    ; прокрутка: вертикаль всегда 0, горизонталь — из переменной
    lda #$00
    sta $2005
    lda _scroll_x
    sta $2005

    ; включаем NMI и выставляем базовые адреса таблиц
    lda _ppu_ctrl_val
    sta $2000

    inc _frame_counter

    pla
    tay
    pla
    tax
    pla
    rti

; ---------- обработчик IRQ (не используется) ----------
irq:
    rti

; ---------- векторы ----------
.segment "VECTORS"
    .word nmi
    .word reset
    .word irq
